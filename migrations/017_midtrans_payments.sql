CREATE TABLE billing_payment_orders (
  id VARCHAR(50) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  organization_id BIGINT UNSIGNED NOT NULL,
  created_by_user_id BIGINT UNSIGNED NOT NULL,
  request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  environment ENUM('sandbox','production') NOT NULL,
  kind ENUM('subscription','topup') NOT NULL,
  amount_idr BIGINT UNSIGNED NOT NULL,
  purchase_snapshot JSON NOT NULL,
  status ENUM('creating','pending','paid','expired','cancelled','denied','needs_review') NOT NULL DEFAULT 'creating',
  snap_token VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NULL,
  provider_status VARCHAR(30) NULL,
  provider_transaction_id VARCHAR(100) NULL,
  fulfillment JSON NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  paid_at DATETIME NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_payment_request (organization_id, request_id),
  UNIQUE KEY uq_payment_provider_transaction (environment, provider_transaction_id),
  INDEX idx_payment_org_time (organization_id, created_at, id),
  CONSTRAINT ck_payment_positive CHECK (amount_idr > 0),
  CONSTRAINT fk_payment_organization FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE RESTRICT,
  CONSTRAINT fk_payment_creator FOREIGN KEY (created_by_user_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
