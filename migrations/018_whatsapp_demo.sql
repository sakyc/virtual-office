CREATE TABLE demo_access (
  user_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
  phone_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  pending_phone_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  otp_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  otp_expires_at DATETIME NULL,
  otp_attempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
  verified_at DATETIME NULL,
  activation_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  activation_expires_at DATETIME NULL,
  activation_attempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
  last_sent_at DATETIME NULL,
  send_window_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  sends SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  organization_id BIGINT UNSIGNED NULL,
  workspace_id BIGINT UNSIGNED NULL,
  activated_at DATETIME NULL,
  expires_at DATETIME NULL,
  credit_idr BIGINT UNSIGNED NOT NULL DEFAULT 3000,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_demo_phone (phone_hash),
  UNIQUE KEY uq_demo_organization (organization_id),
  UNIQUE KEY uq_demo_workspace (workspace_id),
  CONSTRAINT ck_demo_attempts CHECK (otp_attempts <= 5 AND activation_attempts <= 5),
  CONSTRAINT ck_demo_credit CHECK (credit_idr BETWEEN 1 AND 10000),
  CONSTRAINT ck_demo_activation CHECK ((activated_at IS NULL AND expires_at IS NULL AND organization_id IS NULL AND workspace_id IS NULL) OR (activated_at IS NOT NULL AND expires_at > activated_at AND organization_id IS NOT NULL AND workspace_id IS NOT NULL)),
  CONSTRAINT fk_demo_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT,
  CONSTRAINT fk_demo_org FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE RESTRICT,
  CONSTRAINT fk_demo_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
