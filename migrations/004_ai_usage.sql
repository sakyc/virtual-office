CREATE TABLE ai_usage (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  organization_id BIGINT UNSIGNED NOT NULL,
  workspace_id BIGINT UNSIGNED NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  operation ENUM('chat','job','revision') NOT NULL,
  resource_id BIGINT UNSIGNED NULL,
  agent_id VARCHAR(100) NOT NULL,
  provider VARCHAR(40) NOT NULL,
  model VARCHAR(150) NOT NULL,
  provider_message_id VARCHAR(191) NULL,
  status ENUM('started','completed','unknown') NOT NULL DEFAULT 'started',
  input_tokens BIGINT UNSIGNED NULL,
  output_tokens BIGINT UNSIGNED NULL,
  cache_read_tokens BIGINT UNSIGNED NULL,
  cache_creation_tokens BIGINT UNSIGNED NULL,
  started_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  finished_at DATETIME NULL,
  INDEX idx_ai_usage_workspace_time (organization_id, workspace_id, started_at),
  INDEX idx_ai_usage_user_time (user_id, started_at),
  INDEX idx_ai_usage_status_time (status, started_at),
  CONSTRAINT fk_ai_usage_organization FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE RESTRICT,
  CONSTRAINT fk_ai_usage_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces(id) ON DELETE RESTRICT,
  CONSTRAINT fk_ai_usage_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
